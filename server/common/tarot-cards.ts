export function getDreamMessage(cardName: string, isReversed: boolean): string {
  const messages = DREAM_MESSAGES_BY_CARD[cardName];
  if (!messages) {
    const defaults = isReversed ? DREAM_RESPONSES.comfort : DREAM_RESPONSES.encouragement;
    return defaults[Math.floor(Math.random() * defaults.length)];
  }
  const list = isReversed ? messages.reversed : messages.upright;
  return list[Math.floor(Math.random() * list.length)];
}

export function getRandomGreeting(): string {
  return DREAM_RESPONSES.greeting[Math.floor(Math.random() * DREAM_RESPONSES.greeting.length)];
}
